#!/usr/bin/env node
// Generate catalog/skills.json and catalog/README.md from SKILL.md frontmatter + manifest.yaml + evals.
// Deterministic (no timestamps), so `--check` can detect drift in CI.
import fs from 'node:fs';
import path from 'node:path';
import { loadSkills, REPO_ROOT } from '../src/catalog.js';

const check = process.argv.includes('--check');
const pkg = JSON.parse(fs.readFileSync(path.join(REPO_ROOT, 'package.json'), 'utf8'));

const skills = loadSkills().map((s) => {
  const fm = s.frontmatter ?? {};
  const md = fm.metadata ?? {};
  const m = s.manifest ?? {};
  const cases = s.evals?.cases ?? [];
  const kinds = [...new Set(cases.map((c) => c.kind))].sort();
  const routingCases = cases.filter((c) => c.routing === true).length;
  return {
    id: fm.name,
    description: fm.description,
    category: md.category ?? s.category,
    path: `${s.relDir}/SKILL.md`,
    version: md.version,
    maturity: md.maturity,
    risk: md.risk,
    license: fm.license,
    owner: m.owner,
    provenance: m.provenance,
    routing: { intents: m.routing?.intents ?? [], triggers: m.routing?.triggers ?? [], avoid: m.routing?.avoid ?? [], pairs_with: m.routing?.pairs_with ?? [] },
    local_permissions: m.local_permissions ?? [],
    capabilities: { required: m.capabilities?.required ?? [], optional: m.capabilities?.optional ?? [] },
    approvals: m.approvals ?? [],
    verified_agents: m.verified_agents ?? [],
    evaluation: {
      cases: cases.length,
      kinds,
      routing_cases: routingCases,
      status: `${routingCases} routing case(s) checked offline by scripts/run-evals.js; ${cases.length} behaviour case(s) written, not yet run against an agent`,
    },
    links: { skill: `${s.relDir}/SKILL.md`, manifest: `${s.relDir}/manifest.yaml`, evals: `${s.relDir}/evals/cases.yaml` },
  };
});

const catalog = { schema_version: 1, generated_by: 'scripts/build-catalog.js', package: pkg.name, version: pkg.version, skills };
const json = JSON.stringify(catalog, null, 2) + '\n';

const byCat = new Map();
for (const s of skills) byCat.set(s.category, [...(byCat.get(s.category) ?? []), s]);
const lines = [
  '# Skill catalog',
  '',
  '_Generated by `scripts/build-catalog.js` from each skill\'s `SKILL.md` and `manifest.yaml`. Do not edit by hand._',
  '',
  `${skills.length} skills. Maturity labels: draft → community → reviewed → verified (see docs/evaluation-guide.md). All skills here are **draft**: they pass format, security-scan and routing checks, but behaviour evaluations against real agents have not been run yet.`,
  '',
];
for (const [cat, list] of [...byCat.entries()].sort()) {
  lines.push(`## ${cat}`, '', '| Skill | What it does | Risk | External capabilities | Approvals |', '|---|---|---|---|---|');
  for (const s of list) {
    const caps = [...s.capabilities.required.map((c) => `${c.id} (${c.access}, required)`), ...s.capabilities.optional.map((c) => `${c.id} (${c.access}, optional)`)].join('<br>') || '—';
    const appr = s.approvals.map((a) => a.action).join(', ') || '—';
    const desc = s.description.replace(/\|/g, '\\|').split(/(?<=\.)\s/)[0];
    lines.push(`| [${s.id}](../${s.path}) | ${desc} | ${s.risk} | ${caps} | ${appr} |`);
  }
  lines.push('');
}
lines.push('## Install', '', 'With the [Vercel `skills` CLI](https://github.com/vercel-labs/skills) (check `npx skills --help` for current flags):', '', '```bash', 'npx skills add paulsagar7796-cmyk/Universal-agent-skills --list', 'npx skills add paulsagar7796-cmyk/Universal-agent-skills --skill project-initializer --skill software-engineer -a claude-code', '```', '');
const md = lines.join('\n');

const targets = [[path.join(REPO_ROOT, 'catalog', 'skills.json'), json], [path.join(REPO_ROOT, 'catalog', 'README.md'), md]];
if (check) {
  const stale = targets.filter(([f, c]) => !fs.existsSync(f) || fs.readFileSync(f, 'utf8') !== c).map(([f]) => path.relative(REPO_ROOT, f));
  if (stale.length) {
    console.log(`catalog is out of date: ${stale.join(', ')} — run node scripts/build-catalog.js`);
    process.exit(1);
  }
  console.log(`catalog up to date (${skills.length} skills).`);
} else {
  fs.mkdirSync(path.join(REPO_ROOT, 'catalog'), { recursive: true });
  for (const [f, c] of targets) fs.writeFileSync(f, c);
  console.log(`wrote catalog for ${skills.length} skills.`);
}
