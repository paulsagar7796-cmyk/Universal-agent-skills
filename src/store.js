import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { parse, stringify, parseFrontmatter } from './yaml.js';
import { FACT_SCHEMA_VERSION, validateFactsDoc } from './facts.js';
import { assertNoSecrets } from './secrets.js';
import { exists, isDir, readText, readTextIfExists, sha256, withLock, writeFileAtomic } from './util.js';

export const TEMPLATE_DIR = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..', 'templates', 'project-brain');
const FACTS_HEADER = 'Structured project claims. Managed by the `brain` CLI; comments in this file are not preserved.\nstatus: verified | observed | assumption | unknown | disputed | deprecated';

export class StaleWriteError extends Error {
  constructor(file) {
    super(`${file} changed on disk since it was read (another agent or person edited it). Re-run the command to merge against the latest version.`);
    this.name = 'StaleWriteError';
  }
}

/** Replace (or append) a generated section delimited by HTML comment markers. Human text outside markers is preserved. */
export function replaceGenerated(text, name, content) {
  const begin = `<!-- brain:generated:${name}:begin (do not edit inside; regenerated by the brain CLI) -->`;
  const end = `<!-- brain:generated:${name}:end -->`;
  const block = `${begin}\n${content.trimEnd()}\n${end}`;
  const re = new RegExp(`<!-- brain:generated:${name}:begin[^>]*-->[\\s\\S]*?<!-- brain:generated:${name}:end -->`);
  if (re.test(text)) return text.replace(re, () => block);
  return `${text.trimEnd()}\n\n${block}\n`;
}

export function getGenerated(text, name) {
  const m = text.match(new RegExp(`<!-- brain:generated:${name}:begin[^>]*-->\\n?([\\s\\S]*?)\\n?<!-- brain:generated:${name}:end -->`));
  return m ? m[1] : null;
}

/** Split Markdown into { heading: body } by level-2 headings. */
export function markdownSections(text) {
  const out = {};
  let current = '_preamble';
  out[current] = [];
  for (const line of text.split('\n')) {
    const m = line.match(/^##\s+(.+?)\s*$/);
    if (m) {
      current = m[1].toLowerCase();
      out[current] = [];
    } else out[current].push(line);
  }
  return Object.fromEntries(Object.entries(out).map(([k, v]) => [k, v.filter((l) => !/^<!-- brain:generated:/.test(l.trim())).join('\n').trim()]));
}

export class BrainStore {
  constructor(project) {
    this.project = project;
    this.root = project.root;
    this.dir = project.brainDir;
  }

  p(...parts) {
    return path.join(this.dir, ...parts);
  }

  exists() {
    return isDir(this.dir);
  }

  localDir() {
    return this.p('local');
  }

  /** Copy template files that are missing. Never overwrites existing files. Returns created relative paths. */
  scaffold() {
    const created = [];
    const walk = (src, rel) => {
      for (const ent of fs.readdirSync(src, { withFileTypes: true })) {
        const s = path.join(src, ent.name);
        const r = path.join(rel, ent.name);
        const d = this.p(r);
        if (ent.isDirectory()) {
          fs.mkdirSync(d, { recursive: true });
          walk(s, r);
        } else if (!exists(d)) {
          fs.mkdirSync(path.dirname(d), { recursive: true });
          fs.copyFileSync(s, d, fs.constants.COPYFILE_EXCL);
          created.push(r);
        }
      }
    };
    fs.mkdirSync(this.dir, { recursive: true });
    walk(TEMPLATE_DIR, '');
    fs.mkdirSync(this.localDir(), { recursive: true });
    return created;
  }

  loadFacts() {
    const file = this.p('facts.yaml');
    const text = readTextIfExists(file);
    if (text === null) return { doc: { schema_version: FACT_SCHEMA_VERSION, facts: [] }, hash: null, errors: [] };
    let doc;
    try {
      doc = parse(text) ?? {};
    } catch (e) {
      return { doc: { schema_version: FACT_SCHEMA_VERSION, facts: [] }, hash: sha256(text), errors: [`facts.yaml: ${e.message}`], unreadable: true };
    }
    if (doc.facts === null || doc.facts === undefined) doc.facts = [];
    return { doc, hash: sha256(text), errors: validateFactsDoc(doc) };
  }

  /**
   * Validated, locked, optimistic-concurrency write of facts.yaml.
   * `mutate(doc)` receives the freshly loaded document; the write aborts if validation or the secret scan fails.
   */
  updateFacts(mutate, { expectedHash } = {}) {
    return withLock(this.p('local', 'facts.lock'), () => {
      const { doc, hash, errors, unreadable } = this.loadFacts();
      if (unreadable) throw new Error(`facts.yaml cannot be parsed; fix it before writing: ${errors.join('; ')}`);
      if (expectedHash !== undefined && expectedHash !== hash) throw new StaleWriteError('facts.yaml');
      const result = mutate(doc);
      const errs = validateFactsDoc(doc);
      if (errs.length) throw new Error(`facts.yaml would become invalid:\n  - ${errs.join('\n  - ')}`);
      const text = stringify(doc, { header: FACTS_HEADER });
      assertNoSecrets(text, 'facts.yaml');
      writeFileAtomic(this.p('facts.yaml'), text);
      this.regenerateViews(doc);
      return result;
    });
  }

  /** Rewrite generated sections of the human-readable views from facts.yaml + ADRs. */
  regenerateViews(doc = this.loadFacts().doc) {
    const facts = doc.facts ?? [];
    const fmt = (f, extra) => `- **${f.id}** ${f.question ?? f.claim}${extra ? ` — ${extra}` : ''}`;
    const views = [
      ['assumptions.md', 'assumptions', facts.filter((f) => f.status === 'assumption').map((f) => fmt(f, f.test_by ? `test by: ${f.test_by}` : 'how to test: not stated'))],
      ['open-questions.md', 'questions', facts.filter((f) => f.status === 'unknown').map((f) => fmt(f))],
      ['open-questions.md', 'disputed', facts.filter((f) => f.status === 'disputed').map((f) => fmt(f, `conflicts with ${(f.conflicts_with ?? []).join(', ') || 'unspecified'}`))],
    ];
    for (const [file, name, lines] of views) {
      const p = this.p(file);
      const cur = readTextIfExists(p) ?? `# ${file.replace('.md', '')}\n`;
      const heading = name === 'disputed' ? '### Disputed claims\n\n' : '';
      const next = replaceGenerated(cur, name, heading + (lines.length ? lines.join('\n') : '_None._'));
      if (next !== cur) writeFileAtomic(p, next);
    }
    const decisions = this.listDecisions();
    const idx = this.p('decisions', 'index.md');
    const cur = readTextIfExists(idx) ?? '# Decisions\n';
    const lines = decisions.map((d) => `- [${d.id}](${d.file}) ${d.title} — **${d.status}**${d.date ? ` (${d.date})` : ''}`);
    const next = replaceGenerated(cur, 'decisions', lines.length ? lines.join('\n') : '_No decisions recorded._');
    if (next !== cur) writeFileAtomic(idx, next);
  }

  listDecisions() {
    const dir = this.p('decisions');
    if (!isDir(dir)) return [];
    return fs
      .readdirSync(dir)
      .filter((f) => /^ADR-\d{4,}.*\.md$/.test(f))
      .sort()
      .map((file) => {
        const text = readText(path.join(dir, file));
        const fm = parseFrontmatter(text);
        const d = fm.data ?? {};
        return { id: d.id ?? file.match(/^(ADR-\d+)/)[1], title: d.title ?? file, status: d.status ?? 'unknown', date: d.date ?? null, file, body: fm.body, error: fm.error };
      });
  }

  nextDecisionId() {
    const nums = this.listDecisions().map((d) => Number(String(d.id).replace(/\D/g, '')) || 0);
    return `ADR-${String(Math.max(0, ...nums) + 1).padStart(4, '0')}`;
  }

  /** Newest handoff file (by name, which starts with a timestamp). */
  latestHandoff() {
    const dir = this.p('handoffs');
    if (!isDir(dir)) return null;
    const files = fs.readdirSync(dir).filter((f) => /^\d{4}-\d{2}-\d{2}.*\.md$/.test(f)).sort();
    if (!files.length) return null;
    const file = files.at(-1);
    return { file: `handoffs/${file}`, text: readText(path.join(dir, file)) };
  }

  read(rel) {
    return readTextIfExists(this.p(rel));
  }

  /** Canonical files to index: Markdown + YAML under the brain dir, excluding local runtime state. */
  canonicalFiles() {
    const out = [];
    const walk = (dir, rel) => {
      for (const ent of fs.readdirSync(dir, { withFileTypes: true })) {
        if (ent.name.startsWith('.') || (rel === '' && ent.name === 'local')) continue;
        const r = rel ? `${rel}/${ent.name}` : ent.name;
        if (ent.isDirectory()) walk(path.join(dir, ent.name), r);
        else if (/\.(md|ya?ml)$/.test(ent.name)) out.push(r);
      }
    };
    if (this.exists()) walk(this.dir, '');
    return out.sort();
  }

  /** Fingerprint of canonical files (path, size, mtime) — used to decide whether the index is stale. */
  sourceFingerprint() {
    const parts = this.canonicalFiles().map((r) => {
      const st = fs.statSync(this.p(r));
      return `${r}:${st.size}:${Math.floor(st.mtimeMs)}`;
    });
    return sha256(parts.join('\n')).slice(0, 16);
  }
}
